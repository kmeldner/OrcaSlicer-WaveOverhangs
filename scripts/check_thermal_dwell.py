#!/usr/bin/env python3
"""Independently verify the thermal dwell guard's markers and flush blocks in a G-code file.

This is a deliberate second implementation of the accumulator + scheduler + flush sequence (see
docs/thermal_dwell_guard/STAGE1.md §4/§6, STAGE2.md §5/§9 and STAGE3.md §4/§5). It re-walks the
G-code with a NAIVE time model -- distance / feedrate, no acceleration -- and checks the slicer's
markers and inserted flush blocks against it. Because the slicer's estimate IS acceleration-aware,
the two never agree exactly on `acc`; that comparison is tolerance-based (default +/-25%,
--tolerance).

Stage 3 (scheduled flushes). Checks performed:
  1. every FLUSH_POINT's acc is consistent with its sched= kind (forced: at max_time; scheduled:
     at least max_time - lookahead, pulled early by at most lookahead), and close to the naive
     recomputation; the naive scheduler's kinds mostly agree with the slicer's
  2. the inline FLUSH_POINT count equals the SUMMARY count, and SUMMARY scheduled= equals the
     number of non-forced inline markers
  3. ids are 1..N consecutive and the inline markers agree with the SUMMARY entries
  4. per flush block (FLUSH_START..FLUSH_END): markers paired; explicit F on every inserted
     move; travel reaches the configured flush position; wipe pattern present when enabled;
     purge E total == purge_volume/A within 1%; block restores XY/Z to the anchor; retract
     balances back to the anchor's retract state; absolute-E blocks carry `G92 E<anchor>` and
     relative-E blocks do not; the final `G1 F` restores the anchor's modal feedrate
  5. invariant-3 scan: no M104/M109/M140/M106/M620/M621 or filament-cut moves inside any block
  6. (optional, --baseline) pure insertion: stripping the guard's inserted lines from this file
     yields the guard-OFF baseline byte-for-byte
  7. anchor placement: a scheduled flush sits directly after a non-extruding XY travel, and a
     layer_change one before any extrusion of its layer

Stage-2 files (no sched= fields) are still accepted: every point is then treated as forced.

Usage:
    python3 check_thermal_dwell.py <file.gcode> [--baseline off.gcode] [--tolerance 0.25] [-v]
"""

import argparse
import math
import re
import sys

DEFAULT_TOLERANCE = 0.25
PURGE_TOLERANCE = 0.01  # ±1% on the purge volume (STAGE2 §9a)

# Marker grammar (STAGE2 §7 + STAGE3 §7). Load-bearing: keep in sync with ThermalDwellGuard.
RE_CONFIG = re.compile(
    r"^;THERMAL_DWELL_CONFIG flow_max=(\S+) fast_min=(\S+) max_time=(\S+) reset=(\S+) "
    r"melt_zone=(\S+) flush_pos=(\S+) z_lift=(\S+) purge_vol=(\S+) purge_flow=(\S+) wipe=(\d+)"
    r"(?: sched=(\S+) lookahead=(\S+))?"
)
RE_FLUSH_POINT = re.compile(
    r"^;THERMAL_DWELL_FLUSH_POINT id=(\d+) acc=([\d.]+)s layer=(\d+) z=([\d.-]+)"
    r"(?: sched=(\w+) early=([\d.]+)s)?"
)
RE_FLUSH_START = re.compile(r"^;THERMAL_DWELL_FLUSH_START id=(\d+)")
RE_FLUSH_END = re.compile(r"^;THERMAL_DWELL_FLUSH_END id=(\d+)")
RE_SUMMARY = re.compile(
    r"^;THERMAL_DWELL_SUMMARY count=(\d+)(?: total_purge_mm3=(\S+) est_added_time_s=(\S+))?"
    r"(?: scheduled=(\d+))?"
)
RE_POINT = re.compile(
    r"^;THERMAL_DWELL_POINT id=(\d+) layer=(\d+) z=([\d.-]+) acc=([\d.]+)"
    r"(?: sched=(\w+) early=([\d.]+))?"
)

# Filament diameter is needed to turn dE into mm^3 and is NOT part of the CONFIG echo; it comes
# from the config block Orca appends to the end of the file.
RE_FIL_DIAM = re.compile(r"^; filament_diameter\s*=\s*([\d.]+)")

RE_WORD = re.compile(r"([A-Za-z])\s*(-?[\d.]+)")

# Any THERMAL_DWELL_* line the guard inserts (used by the pure-insertion check).
RE_TD_ANY = re.compile(r"^;THERMAL_DWELL_")

# Orca's layer-change tag; the first travel after it is the layer-change break (STAGE3 §3).
RE_LAYER_CHANGE = re.compile(r"^;LAYER_CHANGE\b")

# Orca's embedded config-block dump lines ("; key = value"). These legitimately differ between a
# guard-ON and guard-OFF slice (the enable flag + any changed thermal_dwell_* values), and SPEC
# §6 explicitly carves them out of the byte-identical guarantee, so the pure-insertion check
# ignores them in BOTH files and compares only the real toolpath + our inserted blocks.
RE_CONFIG_DUMP = re.compile(r"^;\s*[A-Za-z0-9_]+\s*=")

# Non-deterministic header lines that differ between any two slices of the same input (wall-clock
# stamp), independent of the guard. Excluded from the pure-insertion comparison in both files.
RE_VOLATILE = re.compile(r"^; generated by ")

# Invariant-3 (STAGE2 §3): commands a flush must NEVER contain -- temperatures, fans, AMS,
# filament cut. Matched as whole G/M-codes at the start of a stripped line.
RE_FORBIDDEN = re.compile(r"^(M104|M109|M140|M190|M106|M620|M621|M628|M629|G29)\b")

SCHED_KINDS = ("forced", "layer_change", "travel")


def print_error(msg):
    print(f"\033[91m[FAIL]\033[0m {msg}")


def print_ok(msg):
    print(f"\033[92m[PASS]\033[0m {msg}")


def print_info(msg):
    print(f"\033[94m[INFO]\033[0m {msg}")


def parse_words(line):
    """Split a G-code line's parameters into {letter: value}, ignoring any comment."""
    code = line.split(";", 1)[0]
    return {m.group(1).upper(): float(m.group(2)) for m in RE_WORD.finditer(code)}


class NaiveAccumulator:
    """The §4 state machine again (standalone: no scope), fed by a no-acceleration time model.

    Mirrors ThermalDwellAccumulator deliberately rather than sharing code: a bug copied into
    both implementations would be invisible, which would defeat the point of this script.
    """

    def __init__(self, cfg):
        self.cfg = cfg
        self.acc = 0.0
        self.fast_vol = 0.0
        self.count = 0

    def step(self, is_extrusion, duration, volume):
        if is_extrusion:
            q = volume / duration if duration > 0.0 else math.inf
            if q <= self.cfg["q_slow"]:
                self.fast_vol = 0.0
                self.acc += duration
                return self._check()
            if q < self.cfg["q_fast"]:
                return None
            if self.cfg["reset"] == "OnVolume":
                if self.fast_vol + volume >= self.cfg["v_melt"]:
                    self._reset_episode()
                else:
                    self.fast_vol += volume
                return None
            self._reset_episode()
            return None

        if self.cfg["reset"] == "OnTravel":
            self._reset_episode()
            return None
        if self.acc > 0.0:
            self.acc += duration
            return self._check()
        return None

    def _reset_episode(self):
        self.acc = 0.0
        self.fast_vol = 0.0

    def _check(self):
        if self.cfg["t_max"] <= 0.0 or self.acc < self.cfg["t_max"]:
            return None
        self.count += 1
        event = {"id": self.count, "acc": self.acc}
        self._reset_episode()
        return event


class NaiveScheduler:
    """STAGE3 §4-§6 again: backward look-ahead onto the latest break in the window, then replay.

    Buffers the current episode's moves; at a crossing picks the latest layer_change break in the
    window (else, under prefer_any_travel, the latest travel), anchors there, and re-runs the moves
    after the break through a fresh accumulator so the live state matches a flush at the break.
    """

    def __init__(self, cfg):
        self.cfg = cfg
        self.acc = NaiveAccumulator(cfg)
        self.mode = cfg.get("sched", "forced_only")
        self.lookahead = cfg.get("lookahead", 0.0)
        self.t = 0.0
        self.buf = []  # [(is_extrusion, duration, volume, kind, t_end, acc_after, index)]
        self.count = 0
        self.layer_change_pending = False
        self.events = []

    def layer_change(self):
        self.layer_change_pending = True

    def step(self, is_extrusion, duration, volume, is_travel, index):
        kind = None
        if is_extrusion:
            self.layer_change_pending = False
        elif is_travel:
            if self.layer_change_pending:
                kind = "layer_change"
                self.layer_change_pending = False
            else:
                kind = "travel"
        self.t += duration
        ev = self.acc.step(is_extrusion, duration, volume)
        if ev is None:
            if self.acc.acc <= 0.0:
                self.buf = []
                return
            self.buf.append((is_extrusion, duration, volume, kind, self.t, self.acc.acc, index))
            while self.buf and self.t - self.buf[0][4] > self.lookahead:
                self.buf.pop(0)
            return

        chosen = self._choose()
        if chosen is None:
            self._emit(ev["acc"], "forced", 0.0, index)
            self.buf = []
            return
        b = self.buf[chosen]
        self._emit(b[5], b[3], self.t - b[4], b[6])
        tail = self.buf[chosen + 1:] + [(is_extrusion, duration, volume, kind, self.t, 0.0, index)]
        sim = NaiveAccumulator(self.cfg)
        kept = []
        for rec in tail:
            ev2 = sim.step(rec[0], rec[1], rec[2])
            if ev2:
                self._emit(ev2["acc"], "forced", 0.0, rec[6])
                kept = []
                continue
            if sim.acc <= 0.0:
                kept = []
                continue
            kept.append(rec[:5] + (sim.acc, rec[6]))
        self.buf = kept
        self.acc.acc = sim.acc
        self.acc.fast_vol = sim.fast_vol

    def _choose(self):
        if self.mode == "forced_only" or self.lookahead <= 0.0:
            return None
        best_travel = None
        for i in range(len(self.buf) - 1, -1, -1):
            rec = self.buf[i]
            if self.t - rec[4] > self.lookahead:
                break
            if rec[3] == "layer_change":
                return i
            if rec[3] == "travel" and self.mode == "prefer_any_travel" and best_travel is None:
                best_travel = i
        return best_travel

    def _emit(self, acc, kind, early, index):
        self.count += 1
        self.events.append({"id": self.count, "acc": acc, "sched": kind, "early": early, "index": index})


def parse_config(lines):
    for line in lines:
        m = RE_CONFIG.match(line)
        if m:
            fx, fy = (float(v) for v in m.group(6).split(","))
            return {
                "q_slow": float(m.group(1)),
                "q_fast": float(m.group(2)),
                "t_max": float(m.group(3)),
                "reset": m.group(4),
                "v_melt": float(m.group(5)),
                "flush_pos": (fx, fy),
                "z_lift": float(m.group(7)),
                "purge_vol": float(m.group(8)),
                "purge_flow": float(m.group(9)),
                "wipe": bool(int(m.group(10))),
                # Stage 3; a Stage-2 file has neither, which means ForcedOnly.
                "sched": m.group(11) or "forced_only",
                "lookahead": float(m.group(12)) if m.group(12) else 0.0,
            }
    return None


def filament_diameter(lines):
    for line in lines:
        m = RE_FIL_DIAM.match(line)
        if m:
            return float(m.group(1))
    return None


def move_deltas(words, pos, absolute_xyz, absolute_e):
    delta = {}
    for axis in ("X", "Y", "Z", "E"):
        if axis not in words:
            delta[axis] = 0.0
            continue
        absolute = absolute_xyz if axis != "E" else absolute_e
        delta[axis] = words[axis] - pos[axis] if absolute else words[axis]
    return delta


def recompute(lines, cfg, diameter):
    """Walk the ORIGINAL G-code (skipping inserted flush blocks) with a naive time model."""
    sched = NaiveScheduler(cfg)
    area = math.pi * (0.5 * diameter) ** 2
    pos = {"X": 0.0, "Y": 0.0, "Z": 0.0, "E": 0.0}
    feedrate = 0.0  # mm/min
    absolute_xyz = True
    absolute_e = True
    in_block = False

    for index, raw in enumerate(lines):
        line = raw.strip()
        if RE_FLUSH_START.match(line):
            in_block = True
            continue
        if RE_FLUSH_END.match(line):
            in_block = False
            continue
        if in_block or not line:
            continue
        if line.startswith(";"):
            if RE_LAYER_CHANGE.match(line):
                sched.layer_change()
            continue

        cmd = line.split()[0].upper()
        if cmd == "G90":
            absolute_xyz = True
            continue
        if cmd == "G91":
            absolute_xyz = False
            continue
        if cmd == "M82":
            absolute_e = True
            continue
        if cmd == "M83":
            absolute_e = False
            continue
        if cmd == "G92":
            for axis, value in parse_words(line).items():
                if axis in pos:
                    pos[axis] = value
            continue
        if cmd == "G4":
            words = parse_words(line)
            dwell = words.get("S", 0.0) + words.get("P", 0.0) / 1000.0
            if dwell > 0.0:
                sched.step(False, dwell, 0.0, False, index)
            continue
        if cmd not in ("G0", "G1"):
            continue

        words = parse_words(line)
        if "F" in words:
            feedrate = words["F"]
        delta = move_deltas(words, pos, absolute_xyz, absolute_e)
        for axis in ("X", "Y", "Z", "E"):
            pos[axis] += delta[axis]

        dist_xyz = math.sqrt(delta["X"] ** 2 + delta["Y"] ** 2 + delta["Z"] ** 2)
        if dist_xyz == 0.0 and delta["E"] == 0.0:
            continue
        moves_xy = delta["X"] != 0.0 or delta["Y"] != 0.0
        is_extrusion = delta["E"] > 0.0 and moves_xy
        is_travel = moves_xy and delta["E"] <= 0.0
        length = dist_xyz if dist_xyz > 0.0 else abs(delta["E"])
        if feedrate <= 0.0:
            continue
        duration = length / (feedrate / 60.0)
        volume = area * delta["E"] if is_extrusion else 0.0
        sched.step(is_extrusion, duration, volume, is_travel, index)

    return sched.events


def collect_anchors_and_blocks(lines):
    """Walk the file, tracking ORIGINAL modal state, and pair each block with its anchor state.

    Returns (blocks, structural_failures). Each block is a dict with the anchor snapshot (state
    just before the FLUSH_POINT), the anchor line (the last original G0/G1 before the marker),
    whether anything extruded since the last ;LAYER_CHANGE, and the raw inserted lines between
    FLUSH_START and FLUSH_END.
    """
    pos = {"X": 0.0, "Y": 0.0, "Z": 0.0, "E": 0.0}
    feedrate = 0.0
    absolute_xyz = True
    absolute_e = True
    retracted = False
    last_move = None             # (line, is_travel)
    extruded_since_layer = True  # before the first ;LAYER_CHANGE nothing counts as "its layer"

    blocks = []
    failures = []
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i].strip()
        fp = RE_FLUSH_POINT.match(line)
        if fp:
            anchor = {
                "id": int(fp.group(1)),
                "sched": fp.group(5) or "forced",
                "early": float(fp.group(6)) if fp.group(6) else 0.0,
                "pos": dict(pos),
                "feedrate": feedrate,
                "absolute_e": absolute_e,
                "retracted": retracted,
                "anchor_line": last_move[0] if last_move else None,
                "anchor_is_travel": last_move[1] if last_move else False,
                "extruded_since_layer": extruded_since_layer,
            }
            # Expect FLUSH_START next, then body, then FLUSH_END.
            j = i + 1
            if j >= n or not RE_FLUSH_START.match(lines[j].strip()):
                failures.append(f"id={anchor['id']}: FLUSH_POINT not followed by FLUSH_START")
                i += 1
                continue
            start_id = int(RE_FLUSH_START.match(lines[j].strip()).group(1))
            body = []
            j += 1
            while j < n and not RE_FLUSH_END.match(lines[j].strip()):
                body.append(lines[j].strip())
                j += 1
            if j >= n:
                failures.append(f"id={anchor['id']}: FLUSH_START without a matching FLUSH_END")
                break
            end_id = int(RE_FLUSH_END.match(lines[j].strip()).group(1))
            if not (anchor["id"] == start_id == end_id):
                failures.append(
                    f"id mismatch across markers: POINT={anchor['id']} START={start_id} END={end_id}"
                )
            blocks.append({"anchor": anchor, "body": body})
            i = j + 1
            continue

        if RE_LAYER_CHANGE.match(line):
            extruded_since_layer = False

        # An ordinary line advances the original-stream modal state (blocks are pure insertion,
        # so they never touch it -- that is exactly Invariant 2).
        if line and not line.startswith(";"):
            cmd = line.split()[0].upper()
            if cmd == "G90":
                absolute_xyz = True
            elif cmd == "G91":
                absolute_xyz = False
            elif cmd == "M82":
                absolute_e = True
            elif cmd == "M83":
                absolute_e = False
            elif cmd == "G92":
                for axis, value in parse_words(line).items():
                    if axis in pos:
                        pos[axis] = value
            elif cmd in ("G0", "G1"):
                words = parse_words(line)
                if "F" in words:
                    feedrate = words["F"]
                delta = move_deltas(words, pos, absolute_xyz, absolute_e)
                for axis in ("X", "Y", "Z", "E"):
                    pos[axis] += delta[axis]
                dxyz = delta["X"] != 0.0 or delta["Y"] != 0.0 or delta["Z"] != 0.0
                moves_xy = delta["X"] != 0.0 or delta["Y"] != 0.0
                if delta["E"] < 0.0 and not dxyz:
                    retracted = True
                elif delta["E"] > 0.0 and delta["X"] == 0.0 and delta["Y"] == 0.0 and delta["Z"] == 0.0:
                    retracted = False
                if dxyz or delta["E"] != 0.0:
                    last_move = (line, moves_xy and delta["E"] <= 0.0)
                if delta["E"] > 0.0 and moves_xy:
                    extruded_since_layer = True
        i += 1

    return blocks, failures


def check_block(block, cfg, area, failures):
    """Validate one inserted flush block against STAGE2 §5/§9 (self-contained per block)."""
    anchor = block["anchor"]
    bid = anchor["id"]
    body = block["body"]

    absolute_e = anchor["absolute_e"]
    # Simulate the block's own effect, starting from the anchor state.
    pos = dict(anchor["pos"])
    retracted = anchor["retracted"]
    absx = True  # blocks always emit absolute-XYZ G1 targets
    saw_g92 = None
    last_f = None
    purge_e = 0.0
    reached_x = reached_y = False
    wipe_moves = 0
    flush_x, flush_y = cfg["flush_pos"]
    purge_feed = round(cfg["purge_flow"] / area * 60.0) if area > 0 else 0

    for line in body:
        if not line or line.startswith(";"):
            continue
        if RE_FORBIDDEN.match(line):
            failures.append(f"id={bid}: forbidden command inside flush block: '{line}'")
        cmd = line.split()[0].upper()
        if cmd == "G92":
            words = parse_words(line)
            if "E" in words:
                saw_g92 = words["E"]
                pos["E"] = words["E"]
            continue
        if cmd not in ("G0", "G1"):
            continue
        words = parse_words(line)
        # Explicit F on every inserted move (unless it is a pure E/G92 helper -- but all our
        # moves carry F, including the final modal-F restore).
        if "F" not in words:
            failures.append(f"id={bid}: inserted move without explicit F: '{line}'")
        else:
            last_f = words["F"]
        delta = move_deltas(words, pos, absx, absolute_e)
        for axis in ("X", "Y", "Z", "E"):
            pos[axis] += delta[axis]
        # Purge = the E move at the purge feedrate.
        if "F" in words and round(words["F"]) == purge_feed and delta["E"] > 0.0:
            purge_e += delta["E"]
        # Retract state through the block (same classification as the original stream).
        dxyz = delta["X"] != 0.0 or delta["Y"] != 0.0 or delta["Z"] != 0.0
        if delta["E"] < 0.0 and not dxyz:
            retracted = True
        elif delta["E"] > 0.0 and delta["X"] == 0.0 and delta["Y"] == 0.0 and delta["Z"] == 0.0:
            retracted = False
        # Flush-position reach + wipe detection.
        if abs(pos["X"] - flush_x) < 1e-2:
            reached_x = True
        if abs(pos["Y"] - flush_y) < 1e-2:
            reached_y = True
        if "X" in words and "Y" in words and abs(pos["Y"] - flush_y) < 1e-2 and delta["X"] != 0.0:
            wipe_moves += 1

    # Travel reached the configured flush position.
    if not (reached_x and reached_y):
        failures.append(
            f"id={bid}: block never reached the flush position {flush_x},{flush_y}"
        )
    # Wipe pattern present iff enabled.
    if cfg["wipe"] and wipe_moves < 2:
        failures.append(f"id={bid}: wipe enabled but no wiper sweep found in block")
    # Purge volume within ±1%.
    want_e = cfg["purge_vol"] / area if area > 0 else 0.0
    if want_e > 0.0 and abs(purge_e - want_e) / want_e > PURGE_TOLERANCE:
        failures.append(
            f"id={bid}: purge E {purge_e:.4f}mm != purge_volume/A {want_e:.4f}mm "
            f"(>{PURGE_TOLERANCE:.0%})"
        )
    # Block restores XY/Z to the anchor.
    for axis in ("X", "Y", "Z"):
        if abs(pos[axis] - anchor["pos"][axis]) > 1e-2:
            failures.append(
                f"id={bid}: {axis} not restored ({pos[axis]:.3f} != anchor {anchor['pos'][axis]:.3f})"
            )
    # Retract balances back to the anchor state.
    if retracted != anchor["retracted"]:
        failures.append(
            f"id={bid}: retract state not restored (block={retracted}, anchor={anchor['retracted']})"
        )
    # E bookkeeping: absolute-E needs G92 E<anchor>; relative-E must not carry one.
    if absolute_e:
        if saw_g92 is None:
            failures.append(f"id={bid}: absolute-E block missing mandatory 'G92 E<anchor>'")
        elif abs(saw_g92 - anchor["pos"]["E"]) > 1e-3:
            failures.append(
                f"id={bid}: G92 E{saw_g92:.5f} != anchor logical E {anchor['pos']['E']:.5f}"
            )
    elif saw_g92 is not None:
        failures.append(f"id={bid}: relative-E block should not emit G92 (found E{saw_g92})")
    # Final modal-F restore matches the anchor.
    if last_f is None or round(last_f) != round(anchor["feedrate"]):
        failures.append(
            f"id={bid}: final modal F {last_f} != anchor feedrate {anchor['feedrate']}"
        )


def check_anchor_placement(block, failures):
    """STAGE3 §3/§8: a scheduled flush sits right after a travel; layer_change before any extrusion."""
    anchor = block["anchor"]
    bid = anchor["id"]
    if anchor["sched"] == "forced":
        return
    if not anchor["anchor_is_travel"]:
        failures.append(
            f"id={bid}: sched={anchor['sched']} but the anchor line is not a non-extruding XY travel: "
            f"'{anchor['anchor_line']}'"
        )
    if anchor["sched"] == "layer_change" and anchor["extruded_since_layer"]:
        failures.append(f"id={bid}: sched=layer_change but the layer had already extruded before the anchor")


def _strip_for_insertion(lines, drop_td):
    """Return the toolpath lines only: drop inserted thermal-dwell blocks/markers (guard-ON) and
    the config-block metadata dump (both files, per SPEC §6)."""
    out = []
    in_block = False
    for raw in lines:
        s = raw.strip()
        if drop_td and RE_FLUSH_START.match(s):
            in_block = True
            continue
        if drop_td and RE_FLUSH_END.match(s):
            in_block = False
            continue
        if in_block:
            continue
        if drop_td and RE_TD_ANY.match(s):  # CONFIG echo, FLUSH_POINT, SUMMARY, POINT lines
            continue
        if RE_CONFIG_DUMP.match(s) or RE_VOLATILE.match(s):
            continue
        out.append(raw)
    return out


def check_pure_insertion(lines, baseline_path, failures):
    """Stripping every guard-inserted line must reproduce the guard-OFF baseline's toolpath."""
    with open(baseline_path, encoding="utf-8", errors="replace") as f:
        baseline = f.read().splitlines()

    stripped = _strip_for_insertion(lines, drop_td=True)
    base_toolpath = _strip_for_insertion(baseline, drop_td=True)

    if stripped == base_toolpath:
        print_ok(
            f"check 6: pure insertion -- guard-ON toolpath == baseline toolpath "
            f"({len(base_toolpath)} lines, config-dump metadata excluded)"
        )
        return
    for idx, (a, b) in enumerate(zip(stripped, base_toolpath)):
        if a != b:
            failures.append(f"pure-insertion mismatch at toolpath line {idx + 1}: '{a}' != baseline '{b}'")
            break
    else:
        failures.append(
            f"pure-insertion length mismatch: stripped {len(stripped)} vs baseline {len(base_toolpath)}"
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("gcode", help="path to a sliced (guard-ON) G-code file")
    parser.add_argument("--baseline", help="guard-OFF slice of the same model, for the pure-insertion check")
    parser.add_argument(
        "--tolerance", type=float, default=DEFAULT_TOLERANCE,
        help="relative tolerance for acc comparisons (default %(default)s)",
    )
    parser.add_argument("--verbose", "-v", action="store_true", help="print every marker")
    args = parser.parse_args()

    with open(args.gcode, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()

    cfg = parse_config(lines)
    if cfg is None:
        print_error("no ;THERMAL_DWELL_CONFIG line found -- was the guard enabled?")
        return 2
    print_info(
        f"config: reset={cfg['reset']} q_slow={cfg['q_slow']} q_fast={cfg['q_fast']} "
        f"t_max={cfg['t_max']} v_melt={cfg['v_melt']} flush_pos={cfg['flush_pos']} "
        f"purge_vol={cfg['purge_vol']} purge_flow={cfg['purge_flow']} wipe={cfg['wipe']} "
        f"sched={cfg['sched']} lookahead={cfg['lookahead']}"
    )

    diameter = filament_diameter(lines)
    if diameter is None:
        print_error("no '; filament_diameter = ' in the config block; cannot convert dE to mm^3")
        return 2
    area = math.pi * (0.5 * diameter) ** 2
    print_info(f"filament diameter: {diameter} mm (area {area:.4f} mm^2)")

    inline = [
        {
            "id": int(m.group(1)), "acc": float(m.group(2)), "layer": int(m.group(3)),
            "z": float(m.group(4)), "sched": m.group(5) or "forced",
            "early": float(m.group(6)) if m.group(6) else 0.0,
        }
        for m in (RE_FLUSH_POINT.match(l) for l in lines) if m
    ]
    summary_points = [
        {
            "id": int(m.group(1)), "layer": int(m.group(2)), "z": float(m.group(3)),
            "acc": float(m.group(4)), "sched": m.group(5) or "forced",
            "early": float(m.group(6)) if m.group(6) else 0.0,
        }
        for m in (RE_POINT.match(l) for l in lines) if m
    ]
    summary_count = None
    summary_scheduled = None
    for line in lines:
        m = RE_SUMMARY.match(line)
        if m:
            summary_count = int(m.group(1))
            summary_scheduled = int(m.group(4)) if m.group(4) else None
            break

    if args.verbose:
        for point in inline:
            print_info(
                f"  FLUSH_POINT id={point['id']} acc={point['acc']}s layer={point['layer']} "
                f"z={point['z']} sched={point['sched']} early={point['early']}s"
            )

    naive_events = recompute(lines, cfg, diameter)
    failures = []
    n_scheduled = sum(1 for p in inline if p["sched"] != "forced")

    # --- Check 1: acc consistent with the sched kind, and the naive model roughly agrees ----
    t_max, look = cfg["t_max"], cfg["lookahead"]
    for point in inline:
        pid, acc, kind, early = point["id"], point["acc"], point["sched"], point["early"]
        if kind not in SCHED_KINDS:
            failures.append(f"id={pid}: unknown sched kind '{kind}'")
            continue
        if acc > t_max * (1.0 + args.tolerance):
            failures.append(f"id={pid}: acc {acc}s overshoots max_time {t_max}s by more than {args.tolerance:.0%}")
        if kind == "forced":
            if acc < t_max:
                failures.append(f"id={pid}: forced flush with acc {acc}s < max_time {t_max}s")
            if early > 1e-6:
                failures.append(f"id={pid}: forced flush reports early={early}s (must be 0)")
        else:
            if cfg["sched"] == "forced_only":
                failures.append(f"id={pid}: sched={kind} although the CONFIG says forced_only")
            if acc < t_max - look - 1e-3:
                failures.append(f"id={pid}: scheduled flush acc {acc}s < max_time - lookahead ({t_max - look:.2f}s)")
            if early < 0.0 or early > look + 1e-3:
                failures.append(f"id={pid}: early={early}s outside [0, lookahead={look}s]")
            if cfg["sched"] == "prefer_layer_change" and kind != "layer_change":
                failures.append(f"id={pid}: sched={kind} although the CONFIG says prefer_layer_change")
    if not any(f.startswith("id=") for f in failures):
        print_ok(
            f"check 1a: all {len(inline)} marker(s) consistent with their sched kind "
            f"({len(inline) - n_scheduled} forced, {n_scheduled} scheduled)"
        )

    # The naive model and the slicer can only be paired point-by-point while they fire the same
    # number of times. Scheduling makes the count depend on timing details at the edge of the
    # look-ahead window (a break 14.9 s vs 15.1 s back flips scheduled/forced and, since a pulled
    # flush relieves less dwell, changes every later crossing), so a count mismatch under a
    # scheduling mode is reported, not failed. ForcedOnly slices must still match exactly.
    if len(naive_events) != len(inline):
        msg = (f"check 1b: naive model found {len(naive_events)} event(s) vs {len(inline)} marker(s)")
        if cfg["sched"] == "forced_only":
            failures.append(msg + " under forced_only (counts must agree)")
        else:
            print_info(msg + "; counts may differ legitimately under scheduling (window-edge timing)")
    else:
        # Compare the dwell at the CROSSING: acc + early reconstructs it for a scheduled point
        # (all time inside an episode counts), so forced vs scheduled pairs are comparable.
        mismatches = []
        kind_disagree = 0
        for point, ev in zip(inline, naive_events):
            if point["sched"] != ev["sched"]:
                kind_disagree += 1
            naive_cross = ev["acc"] + ev["early"]
            slicer_cross = point["acc"] + point["early"]
            if naive_cross <= 0.0:
                continue
            rel = abs(slicer_cross - naive_cross) / naive_cross
            if rel > args.tolerance:
                mismatches.append(
                    f"id={point['id']}: slicer dwell at crossing {slicer_cross:.2f}s vs naive "
                    f"{naive_cross:.2f}s ({rel:.0%} apart)"
                )
        if mismatches:
            failures.extend(mismatches)
        elif naive_events:
            print_ok(f"check 1b: slicer dwell at each crossing within {args.tolerance:.0%} of the naive recomputation")
        if inline:
            # Informational: the kind depends on sub-second timing at the window edge.
            print_info(f"check 1c: naive scheduler agrees on the sched kind for {len(inline) - kind_disagree}/{len(inline)} point(s)")

    # --- Check 2: inline count == SUMMARY count, scheduled= matches -----------------------
    if summary_count is None:
        failures.append("no ;THERMAL_DWELL_SUMMARY line found")
    elif summary_count != len(inline):
        failures.append(f"SUMMARY count={summary_count} but {len(inline)} inline FLUSH_POINT marker(s)")
    elif summary_scheduled is not None and summary_scheduled != n_scheduled:
        failures.append(f"SUMMARY scheduled={summary_scheduled} but {n_scheduled} inline marker(s) are scheduled")
    else:
        print_ok(f"check 2: inline marker count matches SUMMARY count ({summary_count}, scheduled={n_scheduled})")

    # --- Check 3: ids consecutive, inline agrees with SUMMARY ----------------------------
    expected_ids = list(range(1, len(inline) + 1))
    if [p["id"] for p in inline] != expected_ids:
        failures.append(f"inline ids are not 1..N consecutive: {[p['id'] for p in inline]}")
    elif [p["id"] for p in summary_points] != expected_ids:
        failures.append(f"SUMMARY ids are not 1..N consecutive: {[p['id'] for p in summary_points]}")
    else:
        disagreements = [
            f"id={a['id']}: inline (layer={a['layer']} z={a['z']} acc={a['acc']} sched={a['sched']} early={a['early']}) != "
            f"SUMMARY (layer={b['layer']} z={b['z']} acc={b['acc']} sched={b['sched']} early={b['early']})"
            for a, b in zip(inline, summary_points)
            if a["layer"] != b["layer"] or abs(a["z"] - b["z"]) > 1e-3 or abs(a["acc"] - b["acc"]) > 1e-2
            or a["sched"] != b["sched"] or abs(a["early"] - b["early"]) > 1e-2
        ]
        if disagreements:
            failures.extend(disagreements)
        else:
            print_ok("check 3: ids are 1..N and inline markers agree with the SUMMARY block")

    # --- Checks 4 & 5: per-block invariants + invariant-3 scan ----------------------------
    blocks, struct_fail = collect_anchors_and_blocks(lines)
    failures.extend(struct_fail)
    if len(blocks) != len(inline):
        failures.append(f"found {len(blocks)} FLUSH_START/END block(s) but {len(inline)} FLUSH_POINT(s)")
    block_fail_before = len(failures)
    for block in blocks:
        check_block(block, cfg, area, failures)
    if len(failures) == block_fail_before and blocks:
        print_ok(
            f"checks 4 & 5: all {len(blocks)} flush block(s) valid "
            "(paired, explicit F, chute travel, purge, XY/Z + retract + E + F restored, no forbidden cmds)"
        )

    # --- Check 6: pure insertion vs baseline (optional) ----------------------------------
    if args.baseline:
        check_pure_insertion(lines, args.baseline, failures)
    else:
        print_info("check 6: skipped (no --baseline given for the pure-insertion test)")

    # --- Check 7: scheduled anchors sit on breaks (STAGE3) --------------------------------
    placement_before = len(failures)
    for block in blocks:
        check_anchor_placement(block, failures)
    if len(failures) == placement_before:
        if n_scheduled:
            print_ok(f"check 7: all {n_scheduled} scheduled flush(es) anchored on a travel / layer change")
        else:
            print_info("check 7: no scheduled flushes to place-check")

    print()
    if failures:
        for failure in failures:
            print_error(failure)
        print(f"\n\033[91mFAILED\033[0m: {len(failures)} problem(s) found")
        return 1

    print(f"\033[92mPASS\033[0m: {len(inline)} flush point(s) and block(s) verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
